"""Generates tests/cpp/reference_data.hpp with provenance.

Run:  .venv/bin/python tests/reference/generate_references.py
Requires numpy + scipy. Values are produced by SciPy (independent of this
project's C++ integrators) at tolerances far tighter than those used in tests.
"""
import os
import sys
import time

import numpy as np
import scipy
from scipy.integrate import solve_ivp

sys.path.insert(0, os.path.dirname(__file__))
import dust_model_scipy as dm  # noqa: E402

out = []
w = out.append
w("// AUTO-GENERATED by tests/reference/generate_references.py -- do not edit.")
w(f"// numpy {np.__version__}, scipy {scipy.__version__}.")
w("#pragma once")
w("namespace refdata {")


def rober(t, y):
    return [-0.04 * y[0] + 1e4 * y[1] * y[2], 0.04 * y[0] - 1e4 * y[1] * y[2] - 3e7 * y[1] ** 2, 3e7 * y[1] ** 2]


def rober_jac(t, y):
    return [[-0.04, 1e4 * y[2], 1e4 * y[1]], [0.04, -1e4 * y[2] - 6e7 * y[1], -1e4 * y[1]], [0, 6e7 * y[1], 0]]


T_START = time.time()
print('robertson...', flush=True)
tr = [0.4, 4.0, 40.0, 400.0, 4e3, 4e4, 4e5, 4e6]
s = solve_ivp(rober, [0, tr[-1]], [1, 0, 0], method="Radau", rtol=1e-13, atol=[1e-20, 1e-24, 1e-20],
              jac=rober_jac, t_eval=tr)
assert s.success
w("// Robertson problem, y(0) = (1, 0, 0): SciPy Radau, rtol=1e-13, atol=(1e-20, 1e-24, 1e-20), analytic Jacobian.")
w(f"inline constexpr int kRoberN = {len(tr)};")
w("inline constexpr double kRoberT[] = {" + ", ".join(f"{t:.17g}" for t in tr) + "};")
w("inline constexpr double kRoberY[][3] = {" + ", ".join("{" + ", ".join(f"{v:.17g}" for v in s.y[:, i]) + "}"
                                                          for i in range(len(tr))) + "};")

print('vdp...', time.time() - T_START, flush=True)
mu = 1000.0
tv = [500.0, 1000.0, 1500.0, 2000.0, 3000.0]
s = solve_ivp(lambda t, y: [y[1], mu * ((1 - y[0] ** 2) * y[1] - y[0])], [0, tv[-1]], [2, 0], method="LSODA",
              rtol=1e-12, atol=1e-14, jac=lambda t, y: [[0, 1], [mu * (-2 * y[0] * y[1] - 1), mu * (1 - y[0] ** 2)]],
              t_eval=tv)
assert s.success
w("// Van der Pol, mu = 1000, y(0) = (2, 0): SciPy LSODA (ODEPACK), rtol=1e-12, atol=1e-14, analytic Jacobian.")
w(f"inline constexpr int kVdpN = {len(tv)};")
w("inline constexpr double kVdpT[] = {" + ", ".join(f"{t:.17g}" for t in tv) + "};")
w("inline constexpr double kVdpY[][2] = {" + ", ".join("{" + ", ".join(f"{v:.17g}" for v in s.y[:, i]) + "}"
                                                        for i in range(len(tv))) + "};")

w("// Dust model (independent SciPy implementation, tests/reference/dust_model_scipy.py),")
w("// LSODA rtol=1e-10; drift time to r_in = 0.05 au [yr] and final state at r_in.")
w("struct DustRef { double a_cm, r_init_au; bool sed, coag; const char* drag; double t_drift_yr, a_final_rel; };")
w("inline constexpr DustRef kDust[] = {")
cases = [(1e-4, 10, True, False, "both"), (1.0, 10, True, False, "both"), (100.0, 10, True, False, "both"),
         (100.0, 100, False, False, "both"), (10.0, 1, False, False, "epstein"), (1.0, 10, False, True, "both"),
         (0.1, 10, False, True, "both")]
print('dust...', time.time() - T_START, flush=True)
for a, r, sed, coag, drag in cases:
    t, y = dm.drift_time_yr(a, r, sed=sed, coag=coag, drag=drag)
    w(f"    {{{a!r}, {r!r}, {'true' if sed else 'false'}, {'true' if coag else 'false'}, \"{drag}\", {t:.12g}, {y[5]:.12g}}},")
    print(a, r, sed, coag, drag, t, y[5], f'{time.time() - T_START:.0f}s', flush=True)
w("};")
w("}  // namespace refdata")
path = os.path.join(os.path.dirname(__file__), "..", "cpp", "reference_data.hpp")
with open(path, "w") as fh:
    fh.write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path))
