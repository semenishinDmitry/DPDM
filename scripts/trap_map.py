"""Dust traps at the inner edge of a dead zone in a disk with a fossil magnetic field.

Maps (written to docs/science/): trap radius and minimum trapped grain size versus
(i) the density contrast A and width w of the dead-zone edge and (ii) the fossil
field strength B0 (magnetic tension enters beta_K through Eq. 16 of the paper).

The disk is the paper's analytic disk with a parametric edge (ILLUSTRATIVE, not
"Belmondo" output); with real profile tables use disk.model = "tabulated".
Usage: python scripts/trap_map.py [--out docs/science]
"""
import argparse
import os

import numpy as np

import dustppd as dp


def cfg(A=2.0, w=1.0, rb=10.0, B0=0.0, q=0.5, p=1.25):
    c = dp.RunConfig()
    c.disk_model = "self_consistent"
    c.perturbation = "dead_zone_edge"
    c.bump_amplitude, c.bump_width_au, c.bump_r_au = A, w, rb
    c.B0_G, c.br_over_bz, c.field_exponent = B0, q, p
    return c


def trap_radius(c, a):
    t = [z["r_au"] for z in dp.drift_zeros(c, a, 1, 100) if z["stable"]]
    return t[0] if t else np.nan


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/science")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    lines = ["# Dust traps at a dead-zone edge with a fossil field (generated by scripts/trap_map.py)", "",
             "Analytic disk of the paper (alpha = 0.01, Mdot = 1e-8 Msun/yr), beta_K from Eq. (16), edge at",
             "r_b = 10 au with density contrast 1 + A and width w; fossil field B_z = B0 (r/au)^-1.25, B_r = 0.5 B_z.",
             "ILLUSTRATIVE disk structure (no Belmondo tables).", ""]

    # (i) map over (A, w), no field
    As = np.geomspace(0.1, 10, 28)
    ws = np.geomspace(0.2, 5, 24)
    amin = np.full((len(ws), len(As)), np.nan)
    rtr = np.full_like(amin, np.nan)
    for i, w in enumerate(ws):
        for k, A in enumerate(As):
            c = cfg(A=A, w=w)
            amin[i, k] = dp.min_trapped_size(c, 1, 100)
            if np.isfinite(amin[i, k]):
                rtr[i, k] = trap_radius(c, 100.0)
    fig, axs = plt.subplots(1, 2, figsize=(11, 4.2))
    im = axs[0].pcolormesh(As, ws, np.log10(amin), shading="auto", cmap="viridis")
    fig.colorbar(im, ax=axs[0], label="log10 a_min [cm]")
    axs[0].set(xscale="log", yscale="log", xlabel="density contrast A", ylabel="edge width w [au]",
               title="minimum trapped grain size (white: no trap)")
    im = axs[1].pcolormesh(As, ws, rtr, shading="auto", cmap="plasma")
    fig.colorbar(im, ax=axs[1], label="trap radius [au] (a = 1 m)")
    axs[1].set(xscale="log", yscale="log", xlabel="density contrast A", ylabel="edge width w [au]",
               title="trap radius")
    fig.tight_layout()
    fig.savefig(os.path.join(args.out, "trap_map_A_w.png"), dpi=120)
    # trapping threshold A_crit(w): smallest A with a trap
    lines += ["## Trapping threshold of the edge (no field)", "", "| w [au] | A_crit | a_min at A = 2 [cm] |",
              "|---|---|---|"]
    for w in [0.3, 0.5, 1.0, 2.0, 3.0]:
        lo, hi = 1e-3, 100.0
        if np.isnan(dp.min_trapped_size(cfg(A=hi, w=w), 1, 100)):
            lines.append(f"| {w} | > {hi} | - |")
            continue
        for _ in range(50):
            mid = np.sqrt(lo * hi)
            (hi, lo) = (mid, lo) if np.isfinite(dp.min_trapped_size(cfg(A=mid, w=w), 1, 100)) else (hi, mid)
        lines.append(f"| {w} | {hi:.3g} | {dp.min_trapped_size(cfg(A=2.0, w=w), 1, 100):.3g} |")

    # (ii) fossil field
    B0s = np.linspace(0, 3.0, 61)
    sizes = [1e-2, 0.1, 1.0, 100.0]
    res = {a: [trap_radius(cfg(B0=B), a) for B in B0s] for a in sizes}
    amin_B = [dp.min_trapped_size(cfg(B0=B), 1, 100) for B in B0s]
    fig, axs = plt.subplots(1, 2, figsize=(11, 4.2))
    for a in sizes:
        axs[0].plot(B0s, res[a], label=f"a = {a:g} cm")
    axs[0].set(xlabel="B0 [G] (field at 1 au)", ylabel="trap radius [au]",
               title="trap radius vs fossil field (A = 2, w = 1 au)")
    axs[0].legend()
    axs[1].semilogy(B0s, amin_B)
    axs[1].set(xlabel="B0 [G]", ylabel="minimum trapped size [cm]", title="trap is erased by magnetic tension")
    for ax in axs:
        ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(args.out, "trap_vs_field.png"), dpi=120)
    finite = [B for B, a in zip(B0s, amin_B) if np.isfinite(a)]
    Bcrit = max(finite) if finite else 0.0
    lines += ["", "## Effect of the fossil field (A = 2, w = 1 au)", "",
              f"Magnetic tension raises beta_K; the trap disappears for B0 > {Bcrit:.2f} G (grid step 0.05 G),",
              f"i.e. B_z(10 au) > {Bcrit * 10 ** -1.25:.3f} G.", "",
              "| B0 [G] | a_min [cm] | r_trap(1 cm) [au] | r_trap(1 m) [au] |", "|---|---|---|---|"]
    for B in [0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0]:
        c = cfg(B0=B)
        lines.append(f"| {B} | {dp.min_trapped_size(c, 1, 100):.3g} | {trap_radius(c, 1.0):.4g} | "
                     f"{trap_radius(c, 100.0):.4g} |")
    lines += ["", "![trap map](trap_map_A_w.png)", "", "![field](trap_vs_field.png)", ""]
    with open(os.path.join(args.out, "traps.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
