"""Compare dustppd with the values published in Kobozeva (2025).

Usage:  python scripts/compare_paper.py [--out docs]
Writes <out>/validation.md (tables) and <out>/figures/*.png.
Requires the installed package (pip install .) and matplotlib.
"""
import argparse
import os

import numpy as np

import dustppd as dp

# (r_init [au], a_init [cm], paper value) -- copied from the paper.
TABLE1 = [(1, 1, 42.5), (1, 10, 3.8), (1, 100, 2.7), (10, 1, 564), (10, 10, 9.3), (10, 100, 8.1),
          (50, 100, 89.5), (100, 100, 252)]
TABLE2 = [(1, 1e-4, 8.7e3), (1, 0.1, 6.4e3), (1, 1, 2.4e3), (1, 10, 322), (1, 100, 98.2),
          (10, 1e-4, 344e3), (10, 0.1, 155e3), (10, 1, 40e3), (10, 10, 4.9e3), (10, 100, 4.5e3),
          (50, 1e-4, 4.6e6), (50, 0.1, 1.2e6), (50, 1, 183e3), (50, 100, 85e3),
          (100, 1e-4, 14.2e6), (100, 0.1, 2.9e6), (100, 1, 398e3), (100, 100, 306e3)]
TABLE4 = [(1, 1e-4, 7.1e3), (1, 0.1, 2.9e3), (1, 1, 1.2e3), (1, 10, 262), (10, 0.1, 67e3), (10, 1, 22e3),
          (10, 10, 4.3e3), (50, 0.1, 556e3), (50, 1, 165e3)]
# Fig. 12 / Sec. 3.5.2 (from 10 au, coagulation): a_init -> (a_max [cm], t [yr]); Table 3: v_max [m/s]
FIG12 = [(0.1, 15, 67e3, 24.3), (1, 21, 22e3, 123.9), (10, 30, 4.3e3, 55.1), (100, 125, 4.5e3, 157.1)]


def cfg(r, a, sed=True, coag=False):
    c = dp.reference_config()
    c.r_init_au, c.a_init_cm, c.sedimentation, c.coagulation = float(r), float(a), sed, coag
    return c


def fmt(x):
    return "n/a" if x is None or not np.isfinite(x) else f"{x:.4g}"


def row(cells):
    return "| " + " | ".join(cells) + " |"


def flag(ratio, tol):
    return "ok" if abs(ratio - 1) <= tol else "**differs**"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs")
    args = ap.parse_args()
    figdir = os.path.join(args.out, "figures")
    os.makedirs(figdir, exist_ok=True)
    L = ["# Validation against Kobozeva (2025)", "",
         "Generated by `scripts/compare_paper.py` (do not edit by hand). Default (paper) parameters,",
         "analytic disk, calibrated sigma_mol = 1e-16 cm^2 and settle_eps = 0.005 (see physics_model.md).",
         "'ok' = within 5 % (paper values have 2-3 significant figures).", ""]

    L += ["## Table 1: sedimentation times [yr]", "",
          row(["r_init [au]", "a [cm]", "paper", "first entry", "last entry", "ratio (best)", ""]),
          row(["---"] * 7)]
    for r, a, p in TABLE1:
        s = dp.run(cfg(r, a), keep_trajectory=False)["summary"]
        f, l = s["t_settle_first_yr"], s["t_settle_last_yr"]
        cands = [x for x in (f, l) if np.isfinite(x)]
        best = min(cands, key=lambda x: abs(x / p - 1)) if cands else float("nan")
        L.append(row([str(r), str(a), fmt(p), fmt(f), fmt(l), fmt(best / p), flag(best / p, 0.05)]))

    L += ["", "## Table 2: radial-drift times without coagulation [yr] (2D: sedimentation on)", "",
          row(["r_init [au]", "a [cm]", "paper", "dustppd", "ratio", ""]), row(["---"] * 6)]
    for r, a, p in TABLE2:
        t = dp.run(cfg(r, a), keep_trajectory=False)["summary"]["t_drift_yr"]
        L.append(row([str(r), str(a), fmt(p), fmt(t), fmt(t / p), flag(t / p, 0.05)]))

    L += ["", "## Table 4: radial-drift times with coagulation [yr] (radial drift only, as jord++)", "",
          row(["r_init [au]", "a [cm]", "paper", "dustppd", "ratio", ""]), row(["---"] * 6)]
    for r, a, p in TABLE4:
        t = dp.run(cfg(r, a, sed=False, coag=True), keep_trajectory=False)["summary"]["t_drift_yr"]
        L.append(row([str(r), str(a), fmt(p), fmt(t), fmt(t / p), flag(t / p, 0.05)]))

    L += ["", "## Fig. 12 / Table 3: growth from 10 au (coagulation, radial drift only)", "",
          row(["a_init [cm]", "a_max paper", "a_max dustppd", "t paper [yr]", "t dustppd [yr]",
               "v_max paper [m/s]", "v_max dustppd [m/s]"]), row(["---"] * 7)]
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    for a, amax, tp, vp in FIG12:
        res = dp.run(cfg(10, a, sed=False, coag=True))
        s, c = res["summary"], res["columns"]
        L.append(row([str(a), fmt(amax), fmt(s["a_final_cm"]), fmt(tp), fmt(s["t_drift_yr"]), fmt(vp),
                      fmt(s["vr_max_cms"] / 100)]))
        ax1.loglog(c["r_au"], c["a_cm"], label=f"a_init = {a:g} cm")
        ax2.loglog(c["r_au"], np.abs(c["vr_cms"]), label=f"a_init = {a:g} cm")
    ax1.set(xlabel="r [au]", ylabel="a [cm]", title="Growth by coagulation (cf. Fig. 12)")
    ax2.set(xlabel="r [au]", ylabel="|v_r| [cm/s]", title="Drift speed with coagulation (cf. Fig. 13)")
    for ax in (ax1, ax2):
        ax.legend(fontsize=8)
        ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(figdir, "coagulation.png"), dpi=120)

    # Reference case figures (Fig. 6 and 7/8)
    ref = dp.run(dp.reference_config(), check=True)
    s, c = ref["summary"], ref["columns"]
    L += ["", "## Reference case: 1 m from 100 au (Sec. 3.3-3.4, Figs. 6-7)", "",
          row(["quantity", "paper", "dustppd"]), row(["---"] * 3),
          row(["t_sed [yr]", "252", fmt(s["t_settle_first_yr"])]),
          row(["t_drift [kyr]", "306", fmt(s["t_drift_yr"] / 1e3)]),
          row(["max abs(v_r) [m/s]", "58.5", fmt(s["vr_max_cms"] / 100)]),
          row(["r at max |v_r| [au]", "0.31", fmt(s["r_at_vr_max_au"])]),
          row(["abs(v_r) at r_in [m/s]", "33.5", fmt(abs(c["vr_cms"][-1]) / 100)])]
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    ax1.plot(c["r_au"], c["z_au"], lw=0.8)
    ax1.set(xlabel="r [au]", ylabel="z [au]", title="Trajectory z(r), 1 m from 100 au (cf. Fig. 6)")
    for a in [1e-4, 0.1, 1.0, 100.0]:
        cc = dp.run(cfg(100, a))["columns"]
        ax2.loglog(cc["r_au"], np.abs(cc["vr_cms"]), label=f"a = {a:g} cm")
    ax2.set(xlabel="r [au]", ylabel="|v_r| [cm/s]", title="Drift speed, analytic disk (cf. Fig. 8)")
    ax2.legend(fontsize=8)
    for ax in (ax1, ax2):
        ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(figdir, "reference_case.png"), dpi=120)

    L += ["", "![reference case](figures/reference_case.png)", "", "![coagulation](figures/coagulation.png)", ""]
    with open(os.path.join(args.out, "validation.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
